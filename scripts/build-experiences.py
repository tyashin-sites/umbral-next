"""Fold docs/experiences/*.json (agent reports from the Thridify builds) into src/data/experiences.ts.
Specs come only from the parametric model's real geometry. Re-run after any experience changes."""
import json, glob, os
out = {}
def mm(v):
    return f"{v:g} mm"
for f in sorted(glob.glob('docs/experiences/*.json')):
    d = json.load(open(f)); g = d.get('geometry', {})
    specs = []
    if g.get('sightline_mm') is not None:
        if g.get('leaf_sightline_mm'): specs.append(['Sightline, frame / leaf', f"{g['sightline_mm']:g} / {g['leaf_sightline_mm']:g} mm"])
        elif g.get('operable_sightline_mm'): specs.append(['Sightline, fixed / opening', f"{g['sightline_mm']:g} / {g['operable_sightline_mm']:g} mm"])
        else: specs.append(['Sightline', mm(g['sightline_mm'])])
    if g.get('frame_depth_mm'): specs.append(['Frame depth', mm(g['frame_depth_mm'])])
    if g.get('max_panel_w_mm') and g.get('max_panel_h_mm'): specs.append(['Largest leaf in 3D', f"{g['max_panel_w_mm']:g} × {g['max_panel_h_mm']:g} mm"])
    if g.get('glazing'): specs.append(['Glazing', g['glazing'].split('(')[0].strip() if len(g['glazing']) > 34 else g['glazing']])
    if g.get('glazing_bar_mm'): specs.append(['Glazing bar', mm(g['glazing_bar_mm'])])
    if g.get('threshold_mm'): specs.append(['Threshold', mm(g['threshold_mm'])])
    sizes = [s['label'] if isinstance(s, dict) else s for s in d.get('sizes', [])]
    sizes = [s.replace(' (default)', '') for s in sizes]
    out[d['slug']] = {
        'previewId': d['previewId'], 'productId': d.get('productId', ''),
        'sightlineMm': g.get('sightline_mm', 0),
        'finishes': d.get('finishes', []), 'glass': d.get('glass', []), 'sizes': sizes,
        'notes': [{'title': h['title'], 'text': h['text']} for h in d.get('hotspots', [])],
        'specs': [{'label': a, 'value': b} for a, b in specs],
    }
ts = "// GENERATED by scripts/build-experiences.py from docs/experiences/*.json — do not edit by hand.\n"
ts += "import type { Spec } from './collection';\n\n"
ts += "export interface ExperienceData { previewId: string; productId: string; sightlineMm: number; finishes: string[]; glass: string[]; sizes: string[]; notes: { title: string; text: string }[]; specs: Spec[] }\n\n"
ts += "export const EXPERIENCES: Record<string, ExperienceData> = " + json.dumps(out, ensure_ascii=False, indent=2) + ";\n"
open('src/data/experiences.ts', 'w').write(ts)
print('wrote', len(out))
